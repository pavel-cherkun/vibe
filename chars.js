  /* ================= Режим дня ================= */
  const dowOf = (day) => ((day % 7) + 7) % 7; // 0–4 будни, 5–6 выходные
  function inRange(h, a, b) { return a <= b ? h >= a && h < b : h >= a || h < b; }
  function daysOk(spec, day) {
    const d = dowOf(day);
    if (spec == null || spec === "all") return true;
    if (spec === "wd") return d < 5;
    if (spec === "we") return d >= 5;
    if (Array.isArray(spec)) return spec.includes(d);
    return true;
  }
  function stateAt(id, absMin) {
    const c = BY[id];
    const m = absMin == null ? nowMin() : absMin;
    const day = Math.floor(m / 1440), h = (m % 1440) / 60;
    const sc = c ? c.schedule : { wake: 8, sleep: 23.5 };
    const we = dowOf(day) >= 5;
    const wake = we && sc.wakeWe != null ? sc.wakeWe : sc.wake;
    // Для «ночных» (сон после полуночи) день сна — предыдущий
    if (inRange(h, sc.sleep, wake)) return { s: "sleep", label: "спит" };
    if (sc.work && inRange(h, sc.work[0], sc.work[1])) {
      const wd = sc.work[0] > sc.work[1] && h < sc.work[1] ? day - 1 : day;
      if (daysOk(sc.workDays || "wd", wd)) return { s: "work", label: c && c.kind === "acq" && id === "valera" ? "на смене" : "на работе" };
    }
    for (const b of sc.busy || []) {
      if (inRange(h, b[0], b[1]) && daysOk(b[3] || "all", b[0] > b[1] && h < b[1] ? day - 1 : day)) return { s: "busy", label: b[2] };
    }
    return { s: "free", label: "свободен(на)" };
  }
  function nextWake(id, from) {
    let m = from == null ? nowMin() : from;
    for (let i = 0; i < 24 * 6; i++) { if (stateAt(id, m).s !== "sleep") return m; m += 10; }
    return m;
  }
  function lastSeen(id) {
    const now = nowMin();
    if (stateAt(id, now).s === "free") return null;
    let m = now;
    for (let i = 0; i < 24 * 12; i++) { m -= 5; if (stateAt(id, m).s === "free") break; }
    const jitter = (id.length * 7 + Math.floor(m / 1440)) % 9;
    return Math.max(0, m - jitter);
  }
  const clockOf = (m) => { const mm = ((Math.floor(m) % 1440) + 1440) % 1440; return `${String(Math.floor(mm / 60)).padStart(2, "0")}:${String(mm % 60).padStart(2, "0")}`; };
  function status(id) {
    const st = stateAt(id);
    if (st.s === "free") return { s: "free", online: true, t: "в сети", hint: "" };
    const ls = lastSeen(id);
    const day = Math.floor(nowMin() / 1440);
    const when = ls == null ? "недавно" : Math.floor(ls / 1440) < day ? `вчера в ${clockOf(ls)}` : `в ${clockOf(ls)}`;
    let hint = "";
    if (st.s === "sleep") hint = `😴 Спит до ~${clockOf(nextWake(id))} — ответит, когда проснётся`;
    else if (st.s === "work") hint = `💼 ${st.label === "на смене" ? "На смене" : "На работе"} — отвечает с задержкой`;
    else hint = `⏳ Сейчас ${st.label}`;
    return { s: st.s, online: false, t: `был(а) ${when}`, hint, label: st.label };
  }
  // Задержка ответа в игровых минутах
  function replyDelay(id) {
    const c = BY[id];
    const st = stateAt(id);
    const rnd = (a, b) => a + Math.random() * (b - a);
    if (st.s === "sleep") return Math.max(1, nextWake(id) - nowMin()) + rnd(5, 35);
    if (st.s === "work") { const r = (c && c.schedule.workReply) || [15, 60]; return rnd(r[0], r[1]); }
    if (st.s === "busy") return rnd(20, 60);
    const intro = id === "m_3" || id === "m_2";
    return intro ? rnd(3, 12) : rnd(1, 5);
  }
  // План дня по часам (для профиля)
  function plan(id, weekend) {
    const base = Math.floor(nowMin() / 1440);
    let day = base;
    for (let i = 0; i < 7; i++) { if ((dowOf(base + i) >= 5) === !!weekend) { day = base + i; break; } }
    const out = [];
    for (let h = 0; h < 24; h++) out.push(Object.assign({ h }, stateAt(id, day * 1440 + h * 60 + 30)));
    return out;
  }

